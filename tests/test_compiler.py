"""Actual MuLL -> TeX end-to-end tests (explicitly skipped if MuLL absent)."""
import os
import pathlib
import shutil
import subprocess
import tempfile
import unittest

ROOT = pathlib.Path(__file__).resolve().parent.parent
MULL = os.environ.get("MULL", "mull")
ENGINES = os.environ.get("MULL_ENGINES", "cpp,d").split(",")


@unittest.skipUnless(shutil.which(MULL), "requires a MuLL installation from Chubek/mulib")
@unittest.skipUnless(shutil.which("tex"), "requires TeX82/plain TeX")
class CompilerIntegrationTest(unittest.TestCase):
    def compile_run(self, files, needles, runtime_error=None):
        expected_code = None
        for engine in ENGINES:
            with self.subTest(engine=engine):
                code = self.compile_run_engine(files, needles, engine, runtime_error)
                if expected_code is not None:
                    self.assertEqual(code, expected_code, "MuLL hosts emitted different TeX")
                expected_code = code

    def compile_source(self, source, needles, runtime_error=None):
        with tempfile.TemporaryDirectory() as temp:
            path = pathlib.Path(temp) / "source.txp"
            path.write_text(source, encoding="ascii")
            self.compile_run([str(path)], needles, runtime_error)

    def compile_run_engine(self, files, needles, engine, runtime_error):
        with tempfile.TemporaryDirectory() as temp:
            out = pathlib.Path(temp) / "program.tex"
            proc = subprocess.run(
                [str(ROOT / "bin" / "texpresso"), "--mull", MULL, f"--engine={engine}",
                 *[str(ROOT / f) for f in files], "-o", str(out)],
                cwd=ROOT, capture_output=True, text=True, timeout=90,
            )
            self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
            self.assertTrue(out.exists())
            code = out.read_text()
            self.assertNotIn("\\shipout", code.split("% Generated by TeXPresso")[1])
            self.assertNotIn("\\documentclass", code)
            result = subprocess.run(
                ["tex", "-interaction=nonstopmode", "-halt-on-error", out.name],
                cwd=out.parent, capture_output=True, text=True, timeout=90,
            )
            if runtime_error is None:
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            else:
                self.assertNotEqual(result.returncode, 0, result.stdout + result.stderr)
                self.assertIn(runtime_error, result.stdout + result.stderr)
            self.assertIn("No pages of output", result.stdout)
            position = 0
            for needle in needles:
                position = result.stdout.find("\n" + needle + "\n", position)
                self.assertNotEqual(position, -1, result.stdout)
                position += len(needle) + 1
            return code

    def test_hello(self):
        self.compile_run(["examples/hello.txp"], ["Hello from TeXPresso!", "144"])

    def test_factorial(self):
        self.compile_run(["examples/factorial.txp"], ["720"])

    def test_mutation_and_scope(self):
        self.compile_run(["examples/arith.txp"], ["49", "2", "65", "111"])

    def test_imports_out_of_order(self):
        self.compile_run(["examples/modules/app.txp", "examples/modules/math.txp"], ["27", "16"])

    def test_zero_true_false_false(self):
        self.compile_source(
            "(module logic (export main) (define (main) "
            "(println (if 0 19 77)) (println (if #f 19 77))))", ["19", "77"])

    def test_mixed_argument_tags(self):
        self.compile_source("""
            (module tags (export main)
              (define (show a b c d)
                (println a) (println b) (println c) (println d)
                (println (if a 11 12)) (println (not b)))
              (define (increment n flag) (if flag (+ n 1) n))
              (define (main)
                (show 0 #f 7 #t)
                (println (increment 8 #t))))
        """, ["0", "#f", "7", "#t", "11", "#t", "9"])

    def test_recursive_argument_tags(self):
        self.compile_source("""
            (module tags (export main)
              (define (walk flag n)
                (if (= n 0) (if flag 90 91) (walk flag (- n 1))))
              (define (main) (println (walk #f 5)) (println (walk #t 5))))
        """, ["91", "90"])

    def test_nested_call_site_arguments(self):
        self.compile_source("""
            (module calls (export main)
              (define (id n) n)
              (define (encode a b) (+ (* a 10) b))
              (define (main)
                (println (encode 1 (encode 2 (id 3))))
                (println (encode (encode 4 5) (encode 6 7)))))
        """, ["33", "517"])

    def test_recursive_local_slots(self):
        self.compile_source("""
            (module recursion (export main)
              (define (sum n)
                (let ((saved n)) (if (= n 0) 0 (+ (sum (- n 1)) saved))))
              (define (fib n)
                (if (< n 2) n (+ (fib (- n 1)) (fib (- n 2)))))
              (define (main) (println (sum 10)) (println (fib 9))))
        """, ["55", "34"])

    def test_short_circuit_values_and_effects(self):
        self.compile_source("""
            (module logic (export main)
              (define counter 0)
              (define (bump) (set! counter (+ counter 1)) counter)
              (define (main)
                (println (and)) (println (or))
                (println (and 0 7)) (println (or 0 (bump)))
                (println (and #f (bump))) (println counter)
                (println (or #f (bump))) (println counter)))
        """, ["#t", "#f", "7", "0", "#f", "0", "1", "1"])

    def test_compiler_string_escaping(self):
        self.compile_source(r'''
            (module strings (export main)
              (define (main) (println "A#B$C&D_E^F~G\\H%I{J}K")))
        ''', [r"A#B$C&D_E^F~G\H%I{J}K"])

    def test_string_spacing(self):
        self.compile_source(r'''
            (module strings (export main)
              (define (main) (println "A  B   C\tD")))
        ''', ["A  B   C D"])

    def test_bindings_shadow_primitive_procedures(self):
        self.compile_source("""
            (module shadow (export main)
              (define (+ a b) (- a b))
              (define (main) (println (+ 10 4))))
        """, ["6"])

    def test_sequential_binding_can_reuse_a_name(self):
        self.compile_source("""
            (module scope (export main)
              (define (main)
                (println (let* ((x 2) (x (+ x 3))) x))
                (println (let ((x 9)) (let ((x 1) (y x)) y)))))
        """, ["5", "9"])

    def test_long_digit_prefixed_symbol(self):
        self.compile_source("""
            (module symbols (export main)
              (define 999999999999999999999999name 7)
              (define (main) (println 999999999999999999999999name)))
        """, ["7"])

    def test_boolean_argument_cannot_be_used_as_an_integer(self):
        self.compile_source("""
            (module types (export main)
              (define (add a b) (+ a b))
              (define (main) (println (add #f 1))))
        """, [], runtime_error="TeXPresso type error: expected integer")

    def test_division_by_zero(self):
        for operator in ("/", "modulo", "remainder"):
            with self.subTest(operator=operator):
                self.compile_source(
                    f"(module division (export main) (define (main) ({operator} 7 0)))",
                    [], runtime_error="TeXPresso: division by zero")


@unittest.skipUnless(shutil.which(MULL), "requires a MuLL installation from Chubek/mulib")
class CompilerDiagnosticTest(unittest.TestCase):
    def test_check_mull(self):
        for engine in ENGINES:
            with self.subTest(engine=engine):
                result = subprocess.run(
                    [str(ROOT / "bin" / "texpresso"), "--mull", MULL,
                     f"--engine={engine}", "--check-mull", "examples/hello.txp"],
                    cwd=ROOT, capture_output=True, text=True, timeout=90,
                )
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def compile_failure(self, sources, diagnostic):
        for engine in ENGINES:
            for existing in (False, True):
                with self.subTest(engine=engine, existing_output=existing):
                    with tempfile.TemporaryDirectory() as temp:
                        directory = pathlib.Path(temp)
                        files = []
                        for i, source in enumerate(sources):
                            path = directory / f"module{i}.txp"
                            path.write_text(source, encoding="ascii")
                            files.append(str(path))
                        output = directory / "program.tex"
                        original = b"existing output must survive\n"
                        if existing:
                            output.write_bytes(original)
                        result = subprocess.run(
                            [str(ROOT / "bin" / "texpresso"), "--mull", MULL,
                             f"--engine={engine}", *files, "-o", str(output)],
                            cwd=ROOT, capture_output=True, text=True, timeout=90,
                        )
                        self.assertNotEqual(result.returncode, 0, result.stdout)
                        self.assertIn(diagnostic, result.stderr)
                        if existing:
                            self.assertEqual(output.read_bytes(), original)
                        else:
                            self.assertFalse(output.exists())

    def test_private_import_is_not_visible(self):
        self.compile_failure([
            "(module lib (export public) (define private 73) (define public 10))",
            "(module app (import lib) (export main) (define (main) (println private)))",
        ], "unbound identifier app::private")

    def test_ambiguous_import(self):
        self.compile_failure([
            "(module left (export x) (define x 1))",
            "(module right (export x) (define x 2))",
            "(module app (import left right) (export main) (define (main) x))",
        ], "ambiguous imported symbol x")

    def test_unsupported_expressions(self):
        for expression, diagnostic in [
            ("(lambda (x) x)", "closure conversion"),
            ("'(1 2)", "heap backend"),
            ('"not a runtime value"', "unsupported expression type str"),
            ("(letrec ((x 1)) x)", "unresolved procedure"),
        ]:
            with self.subTest(expression=expression):
                self.compile_failure([
                    f"(module app (export main) (define (main) {expression}))",
                ], diagnostic)

    def test_reader_error(self):
        self.compile_failure(["(module app (export main) (define (main) 0)"], "unclosed list")

    def test_wrong_arity(self):
        self.compile_failure([
            "(module app (export main) (define (f x) x) (define (main) (f 1 2)))",
        ], "wrong procedure arity")

    def test_calling_a_local_does_not_fall_back_to_a_global(self):
        for name in ("f", "+"):
            with self.subTest(name=name):
                self.compile_failure([
                    f"(module app (export main) (define ({name} x) x) "
                    f"(define (main) (let (({name} 3)) ({name} 1))))",
                ], "attempt to call a local variable")

    def test_duplicate_parallel_let_binding(self):
        self.compile_failure([
            "(module app (export main) (define (main) (let ((x 1) (x 2)) x)))",
        ], "duplicate let binding")

    def test_out_of_range_integer(self):
        self.compile_failure([
            "(module app (export main) (define (main) 2147483648))",
        ], "integer literal exceeds portable TeX bounds")
